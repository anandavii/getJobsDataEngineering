-- Base schema for a fresh Job Tracker Supabase project.
-- This migration intentionally precedes the inherited incremental migrations.

create table if not exists public.matched_jobs (
  id                  bigint generated by default as identity primary key,
  url                 text not null unique,
  job_title           text not null,
  company             text,
  location            text,
  job_type            text not null default 'Unknown'
                        check (job_type in ('Remote', 'Hybrid', 'On-site', 'Unknown')),
  source              text,
  description_snippet text,
  fetched_at          timestamptz not null default now(),
  date_posted         date,
  salary_min          numeric,
  salary_max          numeric,
  salary_currency     text,
  role_family         text,
  seniority_guess     text,
  fit_score           double precision,
  source_tier         text,
  matched_titles      text,
  matched_skills      text,
  first_seen_at       timestamptz
);

create index if not exists matched_jobs_fetched_at_idx
  on public.matched_jobs (fetched_at desc);

create index if not exists matched_jobs_company_idx
  on public.matched_jobs (company);

create table if not exists public.rejected_jobs (
  id                  bigint generated by default as identity primary key,
  url                 text not null unique,
  job_title           text not null,
  company             text,
  location            text,
  job_type            text not null default 'Unknown'
                        check (job_type in ('Remote', 'Hybrid', 'On-site', 'Unknown')),
  source              text,
  description_snippet text,
  fetched_at          timestamptz not null default now(),
  date_posted         date,
  fit_score           double precision,
  rejection_type      text,
  rejection_reason    text
);

create index if not exists rejected_jobs_fetched_at_idx
  on public.rejected_jobs (fetched_at desc);

alter table public.matched_jobs enable row level security;
alter table public.rejected_jobs enable row level security;

create policy "anon_select_matched_jobs"
  on public.matched_jobs for select to anon using (true);

create policy "anon_select_rejected_jobs"
  on public.rejected_jobs for select to anon using (true);
